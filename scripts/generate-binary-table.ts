/**
 * Generates the static platform package table behind @cpajs/cpa/binary.
 *
 *   node scripts/generate-binary-table.ts          # write src/binary-packages.{cjs,d.cts}
 *   node scripts/generate-binary-table.ts --check  # fail if either file is out of date
 *
 * The literal require.resolve() calls are what lets bundlers such as @vercel/nft
 * trace the optional platform packages. The table is CommonJS because nft only
 * follows require.resolve() in CommonJS input; an ESM table would need its
 * mixedModules option. Target ids and package names come from
 * src/server/targets.ts so the table cannot drift.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { TARGETS, packageName } from '../src/server/targets.ts';
import { ROOT, args, fail, log } from './lib.ts';

const SOURCE = join(ROOT, 'src', 'binary-packages.cjs');
const TYPES = join(ROOT, 'src', 'binary-packages.d.cts');

export interface BinaryTableSource {
  /** src/binary-packages.cjs */
  source: string;
  /** src/binary-packages.d.cts */
  types: string;
}

/** Returns the generated table for the current TARGETS list. */
export function generateBinaryTable(): BinaryTableSource {
  const packages = TARGETS.map((target) => `  '${target.id}': '${packageName(target)}',`).join('\n');
  const resolvers = TARGETS.map(
    (target) => `  '${target.id}': () => require.resolve('${packageName(target)}/package.json'),`,
  ).join('\n');
  const declarations = TARGETS.map((target) => `  readonly '${target.id}': '${packageName(target)}';`).join('\n');

  return {
    source: `/**
 * Static platform package table for \`@cpajs/cpa/binary\`.
 *
 * Generated by scripts/generate-binary-table.ts from TARGETS in
 * src/server/targets.ts; do not edit. Importing the entry (for its side effect)
 * lets bundlers such as @vercel/nft trace the optional platform packages:
 *
 *   import '@cpajs/cpa/binary';
 *
 * Every lookup below is a literal require.resolve() call inside try/catch, so a
 * trace does not depend on the runtime target selection in src/server/binary.ts.
 * This file is CommonJS on purpose: @vercel/nft only follows require.resolve()
 * in CommonJS input.
 */
'use strict';

/** Platform package names by target id. */
const PLATFORM_PACKAGES = {
${packages}
};

const resolvers = {
${resolvers}
};

/**
 * Resolves an installed platform package's package.json, or returns undefined
 * when the package is not installed for this platform.
 */
function resolvePlatformPackage(id) {
  const resolve = resolvers[id];
  if (resolve === undefined) return undefined;
  try {
    return resolve();
  } catch {
    return undefined;
  }
}

module.exports = { PLATFORM_PACKAGES, resolvePlatformPackage };
`,
    types: `/** Generated by scripts/generate-binary-table.ts from TARGETS; do not edit. */
export declare const PLATFORM_PACKAGES: {
${declarations}
};

export type PlatformTargetId = keyof typeof PLATFORM_PACKAGES;

export declare function resolvePlatformPackage(id: string): string | undefined;
`,
  };
}

if (import.meta.main) {
  const values = args({ check: { type: 'boolean' } });
  const generated = generateBinaryTable();
  const files = [
    { path: SOURCE, content: generated.source },
    { path: TYPES, content: generated.types },
  ] as const;

  if (values.check) {
    for (const file of files) {
      const current = await readFile(file.path, 'utf8').catch(() => undefined);
      if (current !== file.content) fail(`${relative(ROOT, file.path)} is out of date; run node scripts/generate-binary-table.ts`);
    }
    log(`${relative(ROOT, SOURCE)} and ${relative(ROOT, TYPES)} are up to date`);
  } else {
    for (const file of files) {
      await writeFile(file.path, file.content);
      log(`wrote ${relative(ROOT, file.path)}`);
    }
  }
}
